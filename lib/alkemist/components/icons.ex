  @doc "The names available as inline SVG."
  @spec builtin() :: [String.t()]
  def builtin, do: Map.keys(@icons)

  @doc "True when `name` is one of the inline icons."
  @spec builtin?(String.t()) :: boolean()
  def builtin?(name), do: Map.has_key?(@icons, name)

  @doc "Renders an icon. Decorative by default (`aria-hidden`); pass `aria-label` to make it meaningful."
  attr :name, :string, required: true, doc: "a `hero-*` icon name"
  attr :class, :any, default: nil
  attr :rest, :global, include: ~w(aria-label aria-hidden role title)

  def icon(%{name: "hero-" <> _ = name} = assigns) do
    assigns = assign(assigns, :paths, Map.get(@icons, name))

    ~H"""
    <svg
      :if={@paths}
      xmlns="http://www.w3.org/2000/svg"
      fill="none"
      viewBox="0 0 24 24"
      stroke-width="1.75"
      stroke="currentColor"
      class={["ak-icon", @class]}
      aria-hidden={if @rest[:"aria-label"], do: nil, else: "true"}
      {@rest}
    >{Phoenix.HTML.raw(@paths)}</svg>
    <span
      :if={!@paths}
      class={[@name, "ak-icon", @class]}
      aria-hidden={if @rest[:"aria-label"], do: nil, else: "true"}
      {@rest}
    />
    """
  end

  def icon(%{name: name}) do
    raise ArgumentError, "Alkemist icons must be Heroicons names starting with \"hero-\", got: #{inspect(name)}"
  end
